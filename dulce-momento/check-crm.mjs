import assert from 'node:assert/strict';
import {recordInquiry,purchaseStats,eligibleRecipients,directory,mergeContacts} from './dist/crm.js';
const input={name:'María',surname:'Rojas',email:' MARIA@correo.test ',phone:'',queryType:'Otra consulta',message:'Quisiera consultar los sabores.'};
const data={customers:[],contacts:[],orders:[],settings:{inactivityDays:180},unsubscribedEmails:[]};
const first=recordInquiry(data,input,'2026-01-01T00:00:00.000Z');
assert.equal(first.marketingConsent,false);assert.equal(first.consentDate,null);
assert.equal(directory(data.customers,data.contacts)[0].segment,'consulta');
recordInquiry(data,{...input,name:'María Isabel',message:'Una segunda consulta distinta.',marketingConsent:true},'2026-02-01T00:00:00.000Z');
assert.equal(data.customers.length,1);assert.equal(data.contacts.length,1);assert.equal(data.contacts[0].history.length,2);
assert.equal(data.contacts[0].consentDate,'2026-02-01T00:00:00.000Z');
recordInquiry(data,input,'2026-03-01T00:00:00.000Z');
assert.equal(data.contacts[0].marketingConsent,true);assert.equal(data.contacts[0].consentDate,'2026-02-01T00:00:00.000Z');
assert.equal(eligibleRecipients(data,{segment:'todos_consentidos'}).length,1);
assert.equal(eligibleRecipients(data,{segment:'nuevo'}).length,0);
const order={orderId:'real-1',customer:{name:'María',email:'maria@correo.test'},createdAt:'2026-01-01T00:00:00.000Z',isDemo:false,payment:{status:'confirmed'},status:'Entregado'};
data.orders=[order];assert.equal(purchaseStats(input.email,data.orders).segment,'nuevo');
data.orders.push({...order,orderId:'real-2',createdAt:'2026-02-01T00:00:00.000Z'});
assert.equal(purchaseStats(input.email,data.orders).segment,'recurrente');
data.orders.push({...order},{...order,orderId:'demo',isDemo:true},{...order,orderId:'failed',payment:{status:'failed'}},{...order,orderId:'cancelled',status:'Cancelado'});
assert.equal(purchaseStats(input.email,data.orders).purchaseCount,2);
assert.equal(purchaseStats(input.email,data.orders,180,Date.parse('2026-08-01')).inactive,true);
assert.equal(purchaseStats(input.email,data.orders,365,Date.parse('2026-08-01')).inactive,false);
assert.equal(purchaseStats(input.email,[{...order,isDemo:true}]).segment,'consulta');
assert.equal(eligibleRecipients(data,{segment:'recurrente'}).length,1);
data.unsubscribedEmails.push('maria@correo.test');
recordInquiry(data,{...input,marketingConsent:true});
assert.equal(eligibleRecipients(data,{segment:'todos_consentidos'}).length,0);
assert.equal(directory([{...data.customers[0],marketingConsent:false,consentDate:null}],data.contacts)[0].marketingConsent,false,'contact copy cannot restore revoked consent');
assert.equal(directory([],[{email:'legacy@test.pe',marketingConsent:true}])[0].marketingConsent,false,'legacy checked-by-default consent has no evidence');
assert.throws(()=>recordInquiry(data,{...input,phone:'invalid'}));
assert.throws(()=>recordInquiry(data,{...input,message:'short'}));
const merged=mergeContacts([{id:'a',email:' MIGRATION@test.pe ',message:'Mensaje anterior',createdAt:'2026-01-01'},{id:'b',email:'migration@test.pe',message:'Mensaje siguiente',createdAt:'2026-02-01'}]);
assert.equal(merged.length,1);assert.equal(merged[0].history.length,2);assert.equal(merged[0].id,'a');
console.log('PASS: inquiry deduplication, history, explicit consent, real purchase segments, configurable inactivity and marketing suppression.');
