import assert from 'node:assert/strict';
globalThis.localStorage={values:new Map(),getItem(key){return this.values.get(key)??null;},setItem(key,value){this.values.set(key,value);}};
const {pageBody,submitInquiry}=await import('./dist/app.js');
const html=pageBody('/contacto');
assert.ok(!html.includes('customerType'));
assert.match(html,/name="marketingConsent"\s*>/);
for(const field of ['name','surname','email','phone','queryType','message'])assert.ok(html.includes(`name="${field}"`));
const result={innerHTML:''};
globalThis.document={querySelector:selector=>selector==='#contact-result'?result:null};
globalThis.FormData=class{constructor(form){return new Map(Object.entries(form.values));}};
const button={disabled:false};
const form={dataset:{},values:{name:'María',surname:'Rojas',email:'Maria@correo.test',queryType:'Otra consulta',message:'Consulta de sabores disponibles.',phone:''},elements:{marketingConsent:{checked:false}},reportValidity:()=>true,querySelector:()=>button,reset(){this.elements.marketingConsent.checked=false;}};
globalThis.fetch=async()=>({ok:false,status:404});
await submitInquiry(form);
let contacts=JSON.parse(localStorage.getItem('dm-contacts'));
assert.equal(contacts.length,1);assert.equal(contacts[0].marketingConsent,false);assert.equal(contacts[0].consentDate,null);
assert.match(result.innerHTML,/Consulta guardada en este navegador/);assert.equal(button.disabled,false);
form.elements.marketingConsent.checked=true;
await submitInquiry(form);
contacts=JSON.parse(localStorage.getItem('dm-contacts'));
assert.equal(contacts.length,1);assert.equal(contacts[0].history.length,2);assert.equal(contacts[0].marketingConsent,true);assert.ok(contacts[0].consentDate);assert.equal(form.elements.marketingConsent.checked,false);
const saved=localStorage.getItem('dm-contacts');
let posted;
globalThis.fetch=async(url,options)=>url.endsWith('/api/email/status')?{ok:true,json:async()=>({backendConfigured:true})}:(posted=JSON.parse(options.body),{ok:true});
await submitInquiry(form);assert.equal(posted.marketingConsent,false);assert.equal(localStorage.getItem('dm-contacts'),saved,'backend inquiry is not duplicated locally');assert.match(result.innerHTML,/recibida correctamente/);
globalThis.fetch=async()=>{throw Error('Servicio no disponible');};
await submitInquiry(form);assert.match(result.innerHTML,/Servicio no disponible/);assert.equal(button.disabled,false);assert.equal(localStorage.getItem('dm-contacts'),saved,'network errors do not silently fall back');
globalThis.location={hostname:'mary123987.github.io'};
globalThis.fetch=()=>{throw Error('No network permitted on static local mode');};
await submitInquiry(form);
const {readLocal}=await import('./dist/local-admin.js');
assert.ok(readLocal().contacts.some(contact=>contact.email==='maria@correo.test'));
assert.match(result.innerHTML,/No se ha enviado a la tienda/);
console.log('PASS: public form fields, unchecked opt-in, local persistence, server submission, reset, failure feedback and GitHub Pages without API requests.');
