const input={name:'Mariana',surname:'Torres',email:'mariana@correo.test',queryType:'Otra consulta',message:'Consulta sobre los sabores disponibles.',marketingConsent:false};
saveLocalInquiry(input);saveLocalInquiry({...input,marketingConsent:true});
assert.equal(readLocal().contacts.filter(c=>c.email===input.email).length,1);
assert.equal(readLocal().contacts.find(c=>c.email===input.email).marketingConsent,true);
const customer=post('customers',{name:'Rosa Pérez',email:'rosa@example.com',status:'activo',marketingConsent:true}).customer;
assert.throws(()=>post('customers',{name:'Otra Rosa',email:'ROSA@example.com',status:'activo'}));
post('customers/'+customer.id,{...customer,name:'Rosa Díaz',marketingConsent:true},'PUT');
assert.equal(readLocal().customers.find(c=>c.id===customer.id).name,'Rosa Díaz');
post('customers/'+customer.id,{},'DELETE');assert.ok(!readLocal().customers.some(c=>c.id===customer.id));
