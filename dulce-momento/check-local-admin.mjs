post('campaigns/'+campaign.id,{...campaign,subject:'Nuevo asunto'},'PUT');
const run=post('send-campaign',{campaignId:campaign.id,transport:'internal',confirmed:true,idempotencyKey:'local-operation'}).run;
assert.ok(run.recipientCount>0);assert.ok(run.results.every(r=>!r.providerId));
