import assert from 'node:assert/strict';
const map=new Map(),sessions=new Map();
const storage=map=>({getItem:key=>map.get(key)??null,setItem:(key,value)=>map.set(key,value),removeItem:key=>map.delete(key)});
globalThis.localStorage=storage(map);globalThis.sessionStorage=storage(sessions);
globalThis.location={hostname:'mary123987.github.io',pathname:'/Dulcemomento/admin'};
globalThis.document={querySelector:selector=>selector==='meta[name="site-base"]'?{content:'/Dulcemomento'}:null,querySelectorAll:()=>[],addEventListener(){},dispatchEvent(){}};
globalThis.window={alert(){},confirm:()=>true};
globalThis.fetch=()=>{throw Error('Local mode must not call the network');};
const {localRequest:request,localMode,readLocal,saveLocalInquiry,presentationAccess}=await import('./dist/local-admin.js');
const post=(path,body,method='POST')=>request('/api/admin/'+path,{method,body:JSON.stringify(body)});
assert.equal(localMode(),true);
assert.throws(()=>post('login',{username:'admin',password:'wrong'}));
post('login',presentationAccess);
const original=readLocal();assert.equal(original.customers.length,9);assert.equal(original.orders.length,10);
